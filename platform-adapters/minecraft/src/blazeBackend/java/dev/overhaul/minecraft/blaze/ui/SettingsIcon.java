    private static final int CELLS = 16;
    private final int[] rows;

    SettingsIcon(int... rows) {
        this.rows = rows;
    }

    /** How wide and tall the icon draws, in GUI units; size 2 is the large one for the page title. */
    static int side(int size) {
        return (int) Math.ceil(CELLS * unit(size));
    }

    private static float unit(int size) {
        double scale = Minecraft.getInstance().getWindow().getGuiScale();
        return (float) (Math.max(1, Math.round(scale / 2)) * size / scale);
    }

    /** Draws the icon centred in a box. */
    void draw(GuiGraphics graphics, int x, int y, int width, int height, int color, int size) {
        double scale = Minecraft.getInstance().getWindow().getGuiScale();
        float unit = unit(size), side = CELLS * unit;
        PoseStack pose = graphics.pose();
        pose.pushPose();
        pose.translate(snap(x + (width - side) / 2, scale), snap(y + (height - side) / 2, scale), 0);
        pose.scale(unit, unit, 1);
        for (int row = 0; row < CELLS; row++) {
            int bits = rows[row];
            for (int start = 0; start < CELLS; start++) {
                if ((bits >> start & 1) == 0) continue;
                int end = start;
                while (end < CELLS && (bits >> end & 1) != 0) end++;
                graphics.fill(start, row, end, row + 1, color);
                start = end;
            }
        }
        pose.popPose();
    }

    private static float snap(float value, double scale) {
        return (float) (Math.round(value * scale) / scale);
    }
