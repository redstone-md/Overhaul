package dev.overhaul.vulkan;

import static org.lwjgl.vulkan.VK10.*;

/** Uncompressed image formats with explicit transfer texel sizes. */
public enum ImageFormat {
    R8_UNORM(VK_FORMAT_R8_UNORM,1), R8_UINT(VK_FORMAT_R8_UINT,1), RG8_UNORM(VK_FORMAT_R8G8_UNORM,2),
    RGBA8_UNORM(VK_FORMAT_R8G8B8A8_UNORM,4), RGBA8_SRGB(VK_FORMAT_R8G8B8A8_SRGB,4),
    BGRA8_UNORM(VK_FORMAT_B8G8R8A8_UNORM,4), BGRA8_SRGB(VK_FORMAT_B8G8R8A8_SRGB,4),
    R16_SFLOAT(VK_FORMAT_R16_SFLOAT,2), RG16_SFLOAT(VK_FORMAT_R16G16_SFLOAT,4),
    RGBA16_SFLOAT(VK_FORMAT_R16G16B16A16_SFLOAT,8), R32_SFLOAT(VK_FORMAT_R32_SFLOAT,4),
    RG32_SFLOAT(VK_FORMAT_R32G32_SFLOAT,8), RGBA32_SFLOAT(VK_FORMAT_R32G32B32A32_SFLOAT,16),
    R8_SNORM(VK_FORMAT_R8_SNORM,1),R8_SINT(VK_FORMAT_R8_SINT,1),
    RG8_SNORM(VK_FORMAT_R8G8_SNORM,2),RG8_UINT(VK_FORMAT_R8G8_UINT,2),RG8_SINT(VK_FORMAT_R8G8_SINT,2),
    RGB8_UNORM(VK_FORMAT_R8G8B8_UNORM,3),RGB8_SNORM(VK_FORMAT_R8G8B8_SNORM,3),RGB8_UINT(VK_FORMAT_R8G8B8_UINT,3),RGB8_SINT(VK_FORMAT_R8G8B8_SINT,3),
    RGBA8_SNORM(VK_FORMAT_R8G8B8A8_SNORM,4),RGBA8_UINT(VK_FORMAT_R8G8B8A8_UINT,4),RGBA8_SINT(VK_FORMAT_R8G8B8A8_SINT,4),
    R16_UNORM(VK_FORMAT_R16_UNORM,2),R16_SNORM(VK_FORMAT_R16_SNORM,2),R16_UINT(VK_FORMAT_R16_UINT,2),R16_SINT(VK_FORMAT_R16_SINT,2),
    RG16_UNORM(VK_FORMAT_R16G16_UNORM,4),RG16_SNORM(VK_FORMAT_R16G16_SNORM,4),RG16_UINT(VK_FORMAT_R16G16_UINT,4),RG16_SINT(VK_FORMAT_R16G16_SINT,4),
    RGB16_UNORM(VK_FORMAT_R16G16B16_UNORM,6),RGB16_SNORM(VK_FORMAT_R16G16B16_SNORM,6),RGB16_UINT(VK_FORMAT_R16G16B16_UINT,6),RGB16_SINT(VK_FORMAT_R16G16B16_SINT,6),RGB16_SFLOAT(VK_FORMAT_R16G16B16_SFLOAT,6),
    RGBA16_UNORM(VK_FORMAT_R16G16B16A16_UNORM,8),RGBA16_SNORM(VK_FORMAT_R16G16B16A16_SNORM,8),RGBA16_UINT(VK_FORMAT_R16G16B16A16_UINT,8),RGBA16_SINT(VK_FORMAT_R16G16B16A16_SINT,8),
    R32_UINT(VK_FORMAT_R32_UINT,4),R32_SINT(VK_FORMAT_R32_SINT,4),RG32_UINT(VK_FORMAT_R32G32_UINT,8),RG32_SINT(VK_FORMAT_R32G32_SINT,8),
    RGB32_UINT(VK_FORMAT_R32G32B32_UINT,12),RGB32_SINT(VK_FORMAT_R32G32B32_SINT,12),RGB32_SFLOAT(VK_FORMAT_R32G32B32_SFLOAT,12),
    RGBA32_UINT(VK_FORMAT_R32G32B32A32_UINT,16),RGBA32_SINT(VK_FORMAT_R32G32B32A32_SINT,16),
    RGB10A2_UNORM(VK_FORMAT_A2B10G10R10_UNORM_PACK32,4),RGB10A2_UINT(VK_FORMAT_A2B10G10R10_UINT_PACK32,4),RG11B10_UFLOAT(VK_FORMAT_B10G11R11_UFLOAT_PACK32,4),
    D16_UNORM(VK_FORMAT_D16_UNORM,2,true),D32_SFLOAT(VK_FORMAT_D32_SFLOAT,4,true),
    D24_UNORM_S8_UINT(VK_FORMAT_D24_UNORM_S8_UINT,4,VK_IMAGE_ASPECT_DEPTH_BIT|VK_IMAGE_ASPECT_STENCIL_BIT),
    D32_SFLOAT_S8_UINT(VK_FORMAT_D32_SFLOAT_S8_UINT,8,VK_IMAGE_ASPECT_DEPTH_BIT|VK_IMAGE_ASPECT_STENCIL_BIT),
    S8_UINT(VK_FORMAT_S8_UINT,1,VK_IMAGE_ASPECT_STENCIL_BIT);
    private final int format, bytes;
    private final int aspects;
    ImageFormat(int format,int bytes){this(format,bytes,false);}
    ImageFormat(int format,int bytes,boolean depth){this(format,bytes,depth?VK_IMAGE_ASPECT_DEPTH_BIT:VK_IMAGE_ASPECT_COLOR_BIT);}
    ImageFormat(int format,int bytes,int aspects){this.format=format;this.bytes=bytes;this.aspects=aspects;}
    public int vkFormat(){return format;}
    public int bytesPerPixel(){return bytes;}
    public boolean isDepth(){return (aspects&VK_IMAGE_ASPECT_DEPTH_BIT)!=0;}
    public int aspectMask(){return aspects;}
    public static ImageFormat fromVk(int format){
        for(ImageFormat value:values())if(value.format==format)return value;
        throw new IllegalArgumentException("Unsupported uncompressed Vulkan image format: "+format);
    }
}
